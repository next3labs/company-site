const sitemap = require("@quasibit/eleventy-plugin-sitemap");
const Image = require("@11ty/eleventy-img");
const path = require("path");

module.exports = function(eleventyConfig) {
  // Copy assets to output directory
  eleventyConfig.addPassthroughCopy("src/assets");

  // Copy CNAME file for custom domain
  eleventyConfig.addPassthroughCopy("src/CNAME");

  // Copy SEO files
  eleventyConfig.addPassthroughCopy("src/robots.txt");
  // llms.txt — plain-text summary for AI assistants / answer engines.
  eleventyConfig.addPassthroughCopy("src/llms.txt");
  // Note: sitemap.xml is now auto-generated by eleventy-plugin-sitemap

  // Watch CSS files for changes
  eleventyConfig.addWatchTarget("src/assets/css/");

  // Auto-generate sitemap.xml with proper lastmod dates
  eleventyConfig.addPlugin(sitemap, {
    sitemap: {
      hostname: "https://next3labs.com",
    },
  });

  // Sitemap allow-list. The sitemap template used to emit `collections.all`,
  // which advertises EVERY page Eleventy renders — that leaked a client
  // proposal and three image-mockup pages to Google (14 Aug 2026). The first
  // fix made publishing opt-OUT, which still auto-published anything added
  // later; this is now an explicit opt-IN list.
  //
  // Every URL that may appear in sitemap.xml. Adding a page to the site is NOT
  // enough to publish it to Google — it must also be listed here. This is an
  // allow-list on purpose: the opt-out version silently published whatever was
  // added next, which is exactly how the client proposal leaked.
  const SITEMAP_ALLOWLIST = new Set([
    "/",
    "/contact/",
    "/privacy/",
    "/terms/",
  ]);

  eleventyConfig.addCollection("sitemapPages", (collectionApi) =>
    collectionApi.getAll().filter((item) => {
      if (item.data.sitemap === false) return false;
      if (item.data.eleventyExcludeFromCollections) return false;
      const url = item.url;
      if (!url) return false;                    // no output (e.g. data files)
      if (url.startsWith("/assets/")) return false; // assets are not pages
      return SITEMAP_ALLOWLIST.has(url);
    })
  );

  // Build-time guard: surface any rendered page that is NOT in the allow-list,
  // so a new page is a deliberate publishing decision rather than an accident.
  eleventyConfig.on("eleventy.after", ({ results }) => {
    const rendered = (results || [])
      .map((r) => r.url)
      .filter((u) => u && !u.startsWith("/assets/"));
    const unlisted = rendered.filter((u) => !SITEMAP_ALLOWLIST.has(u));
    if (unlisted.length) {
      console.log(
        `\n[sitemap] ${rendered.length} pages built, ${SITEMAP_ALLOWLIST.size} in sitemap.\n` +
        `[sitemap] NOT advertised to Google (intended for redirect stubs — check nothing real is here):\n` +
        unlisted.map((u) => `           ${u}`).join("\n") + "\n"
      );
    }
  });

  // Image optimization shortcode
  // Usage: {% image "src/assets/images/photo.jpg", "Alt text", "320, 640, 1024" %}
  eleventyConfig.addShortcode("image", async function(src, alt, sizes = "320, 640, 1024") {
    if (!alt) {
      throw new Error(`Missing \`alt\` attribute on image shortcode for: ${src}`);
    }

    // Parse sizes if it's a string
    const widthsArray = typeof sizes === "string"
      ? sizes.split(",").map(s => parseInt(s.trim()))
      : sizes;

    // Resolve the full path relative to the project root
    const fullPath = path.join(__dirname, src);

    let metadata = await Image(fullPath, {
      widths: widthsArray,
      formats: ["avif", "webp", "jpeg"],
      outputDir: "./_site/assets/images/optimized",
      urlPath: "/assets/images/optimized/",
      filenameFormat: function (id, src, width, format, options) {
        const extension = path.extname(src);
        const name = path.basename(src, extension);
        return `${name}-${width}w.${format}`;
      }
    });

    let imageAttributes = {
      alt,
      sizes: "(max-width: 640px) 320px, (max-width: 1024px) 640px, 1024px",
      loading: "lazy",
      decoding: "async",
    };

    return Image.generateHTML(metadata, imageAttributes);
  });

  // Set custom directories for input, output, includes, and data
  return {
    dir: {
      input: "src",
      includes: "_includes",
      data: "_data",
      output: "_site"
    },
    // Use Nunjucks for HTML files
    htmlTemplateEngine: "njk",
    markdownTemplateEngine: "njk"
  };
};
